// Run against a temporary workspace: node tests/ui-smoke.cjs URL_WITH_TOKEN
const assert = require('node:assert/strict');
const path = require('node:path');
const moduleRoot = process.env.CREATEAPP_PLAYWRIGHT_ROOT || process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES;
const {chromium, webkit} = require(moduleRoot ? path.join(moduleRoot, 'playwright') : 'playwright');

(async () => {
  const url = process.argv[2];
  if (!url) throw new Error('Pass the local CreateApp URL, including #token=.');
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url);
  await page.locator('#layout').waitFor({state:'visible'});
  assert.equal(await page.locator('[name=pack]:checked').count(),5);
  assert.equal(await page.locator('[name=pack][value=matt]').isChecked(),false);
  assert.equal(await page.locator('[name=pack][value=graphify]').isChecked(),false);
  assert.equal(await page.locator('[name=vercel_react]').isChecked(),true);
  await page.screenshot({path:'/tmp/createapp-desktop.png',fullPage:true});
  await page.locator('[name=coordinator]').selectOption('matt');
  assert.equal(await page.locator('[name=pack][value=matt]').isChecked(),true);
  await page.locator('#preview-button').click();
  await page.locator('#review').waitFor({state:'visible'});
  assert.ok((await page.locator('#review-roles').innerText()).includes('ca-matt-workflow'));
  assert.ok(!(await page.locator('#review-roles').innerText()).split(/\s+/).includes('ca-workflow'));
  await page.locator('#edit-button').click();
  await page.locator('[name=coordinator]').selectOption('superpowers');
  await page.locator('[name=pack][value=matt]').uncheck();
  await page.locator('[name=mode][value=rigorous]').check();
  assert.equal(await page.locator('[name=testing]').inputValue(),'strict');
  assert.equal(await page.locator('[name=autonomy]').inputValue(),'guided');
  await page.locator('[name=mode][value=balanced]').check();
  await page.locator('[name=stack]').selectOption('python');
  assert.equal(await page.locator('[name=template]').inputValue(),'config-only');
  await page.locator('#preview-button').click();
  await page.locator('#review').waitFor({state:'visible'});
  assert.ok(!(await page.locator('#review-roles').innerText()).includes('ca-react'));
  await page.locator('#edit-button').click();
  await page.locator('[name=stack]').selectOption('react-vite');
  await page.getByText('Seleccionar skills individuales',{exact:true}).click();
  await page.locator('[name=custom_skills]').check();
  await page.locator('[name=skill][value=debug]').uncheck();
  await page.getByText('Configurar para varios asistentes',{exact:true}).click();
  await page.locator('[name=extra_agent][value=codex]').check();
  await page.locator('[name=goal]').fill('Configurar un proyecto existente con dos asistentes.');
  await page.locator('#preview-button').click();
  await page.locator('#review').waitFor({state:'visible'});
  assert.ok(!(await page.locator('#review-roles').innerText()).includes('ca-debug'));
  await page.locator('#create-button').click();
  await page.locator('#progress-title').filter({hasText:'Tu proyecto está preparado.'}).waitFor({timeout:180000});
  const target=await page.locator('#progress-message').innerText();
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('Chromium: form, presets, optional Matt, stack scoping and real project generation passed.');
  console.log('Generated project:',target);
  await browser.close();
  // Opt into WebKit when its OS dependencies are available; neither engine is a real iPhone.
  const mobileEngine=process.env.CREATEAPP_TEST_WEBKIT==='1'?webkit:chromium;
  const mobileBrowser=await mobileEngine.launch({headless:true});
  const mobile=await mobileBrowser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  await mobile.goto(url);
  // A completed job is displayed after refresh. Return to the form.
  await mobile.locator('#another-button').waitFor({state:'visible'});
  await mobile.locator('#another-button').click();
  await mobile.locator('#layout').waitFor({state:'visible'});
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.screenshot({path:'/tmp/createapp-mobile.png',fullPage:true});
  await mobile.locator('[name=goal]').fill('Interfaz móvil');
  assert.equal(await mobile.locator('[name=goal]').inputValue(),'Interfaz móvil');
  console.log((process.env.CREATEAPP_TEST_WEBKIT==='1'?'WebKit':'Chromium')+': 390px layout and form interaction passed.');
  await mobileBrowser.close();
})().catch(e=>{console.error(e);process.exit(1)});
